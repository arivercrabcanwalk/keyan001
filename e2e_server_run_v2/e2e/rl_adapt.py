"""REVIEW FIX (R-repack): RL-owned morning plan adaptation.
The shared heuristic PA.repack (trim + earliest-finish re-insertion + 2 relocate passes) rewrites most trips of ANY
static plan before execution (measured on TSALNS test plans: ~89 % of targets end up in a different trip, ~12 % at a
different station). For the RL arms this contradicts the claim "all routes are generated by RL". Here every open
station's targets are re-planned by pi_route as a single-station sub-problem with an energy reserve r derived from the
forecast issued at t0 (only information a dispatcher has at t0); the heuristic repack is then applied with
relocate=0 as a pure safety net (trim/re-insert only trips still infeasible) and its edits are counted and reported.
Siting and target->station assignment of the plan are kept (they are pi_site / pi_route decisions)."""
import math
import numpy as np
from .common import ROOT, FE
import sys
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)
from wx2 import inst as I, planadapt as PA   # noqa: E402

_CACHE = {}


def _calm_energy(nodes, st, trip, fe):
    pts = [(st["x"], st["y"])] + [(nodes[n].x, nodes[n].y) for n in trip] + [(st["x"], st["y"])]
    L = sum(math.hypot(a[0] - b[0], a[1] - b[1]) for a, b in zip(pts, pts[1:]))
    return L / 900.0 * fe + sum(nodes[n].energy for n in trip)


def station_reserve(ins, st, d, trips, wx, fc, margin=0.08, rmax=0.5):
    """r such that capacity/(1+r) mimics the forecast energy inflation of this station's planned trips (+ margin)."""
    nodes = I.node_by_id(ins); ratios = []
    for tr in trips:
        if not tr:
            continue
        e, _ = PA._energy(ins, st, d, tr, wx, 0.0, fc)
        ratios.append(e / max(_calm_energy(nodes, st, tr, ins.params.flight_energy), 1e-9))
    if not ratios:
        return 0.0
    return float(np.clip(max(ratios) * (1.0 + margin) - 1.0, 0.0, rmax))


def sig(sol):
    out = {}
    for si, st in enumerate(sol["routes"]):
        for di, tr in enumerate(st):
            for t in tr:
                for n in t:
                    out[n] = (si, di, tuple(t))
    return out


def rl_repack(ins, sol, wx, router_path, margin=0.08):
    """Returns (adapted solution, leftover, stats)."""
    key = (ins.sha256, wx.hash() if hasattr(wx, "hash") else wx.seed, router_path, tuple(sol["station_types"]),
           str(sol["routes"]))
    if key in _CACHE:
        a, l, s = _CACHE[key]; return a, list(l), dict(s)
    from e2e.exec_policy import get_router
    from e2e.route_infer import solve_routes
    from e2e.route_env import decode_actions
    pol = get_router(router_path)
    fc = wx.forecast_wind(0.0, 0.0)
    _, stations, drones = I.open_drones(ins, sol)
    nodes = I.node_by_id(ins)
    new_routes = [[list(map(list, dr)) for dr in s] for s in sol["routes"]]
    n_fail = 0; rs = []
    for st in stations:
        si = st["si"]; kind = st["kind"]
        ds = [d for d in drones if d["sid"] == stations.index(st)]
        trips = [tr for d in ds for tr in d["trips"]]
        nids = [n for tr in trips for n in tr]
        if len(nids) < 2:
            continue
        r = station_reserve(ins, st, ds[0], trips, wx, fc, margin)
        tg = np.array([[nodes[n].x, nodes[n].y] for n in nids]); sxy = np.array([[st["x"], st["y"]]])
        ok = False
        for rr in (r, 0.5 * r, 0.0):
            c, acts = solve_routes(pol, tg, sxy, np.array([kind]), mode="pomo", dev="cpu", reserve=rr, seed=0)
            if np.isfinite(c):
                ok = True; rs.append(rr); break
        if not ok:
            n_fail += 1; continue
        sub = decode_actions(acts, len(nids), 1, [kind])[0]
        new_routes[si] = [[[nids[q] for q in tr] for tr in sub[dr]] for dr in range(2)]
    rl_sol = {k: sol[k] for k in sol}; rl_sol["routes"] = new_routes
    asol, left = PA.repack(ins, rl_sol, wx, margin=margin, t0=0.0, relocate=0)
    a, b = sig(rl_sol), sig(asol)
    nT = max(1, len(a))
    stats = dict(adapt="rl", adapt_r_mean=float(np.mean(rs)) if rs else 0.0, adapt_station_fail=n_fail,
                 safety_trip_changed=sum(1 for n in a if b.get(n, (None, None, None))[2] != a[n][2]) / nT,
                 safety_station_moved=sum(1 for n in a if b.get(n, (None,))[0] != a[n][0]) / nT)
    _CACHE[key] = (asol, list(left), dict(stats))
    return asol, left, stats


def heur_repack(ins, sol, wx, margin=0.08, relocate=2):
    asol, left = PA.repack(ins, sol, wx, margin=margin, t0=0.0, relocate=relocate)
    a, b = sig(sol), sig(asol); nT = max(1, len(a))
    stats = dict(adapt=f"heur{relocate}",
                 safety_trip_changed=sum(1 for n in a if b.get(n, (None, None, None))[2] != a[n][2]) / nT,
                 safety_station_moved=sum(1 for n in a if b.get(n, (None,))[0] != a[n][0]) / nT)
    return asol, left, stats


def adapt(ins, sol, wx, spec=None):
    """spec: None/'heur' (shared heuristic, relocate=2, as before) | 'heur0' | 'rl:<router.pt>'"""
    if spec and spec.startswith("rl:"):
        path = spec[3:]
        import os
        if not os.path.isabs(path):
            path = os.path.join(ROOT, path)
        return rl_repack(ins, sol, wx, path)
    if spec == "heur0":
        return heur_repack(ins, sol, wx, relocate=0)
    return heur_repack(ins, sol, wx, relocate=2)


def n_unservable_all(ins, reqs):
    """REVIEW FIX (R-G3): plan-INDEPENDENT count of structurally unservable requests (not coverable even if every
    candidate station were opened as DABS). The simulator's n_unservable depends on the opened stations, so arms with
    different sitings had different completion denominators."""
    p = ins.params; cnt = 0
    for (t0, x, y, pri, kind, tid) in reqs:
        ok = False
        for s in ins.stations:
            dd = math.hypot(x - s.x, y - s.y)
            if dd <= p.large_radius + 1e-6 and 2 * dd / 900.0 * p.flight_energy + 0.05 <= p.large_battery + 1e-9:
                ok = True; break
        cnt += (not ok)
    return cnt
